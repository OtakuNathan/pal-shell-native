"""Project the production frame admission guard into its finite TLC domain."""
from itertools import product
from pathlib import Path
from runpy import run_path
import sys


ROOT = Path(__file__).resolve().parents[1]
accepts = run_path(str(ROOT / "pal_plugin/pal_shell_native/local_wire.py"))["accepts_frame"]
fields = ("closed", "requested", "known", "sessionId", "outputId", "generation")
booleans = (False, True)
values = (0, 1, 2)


def literal(value):
    return str(value).upper() if isinstance(value, bool) else str(value)


rows = []
for closed, requested, known, session, output, generation in product(
    booleans, booleans, booleans, values, values, (1, 2),
):
    if accepts(closed, requested, session, output, generation, generation + 1, known):
        rows.append("<<" + ", ".join(map(literal, (closed, requested, known, session, output, generation))) + ">>")
text = (
    "---- MODULE LocalAdmission ----\n"
    "\\* Generated by scripts/export_local_admission.py from the production guard.\n"
    "Accept(" + ", ".join(fields) + ") ==\n"
    "    <<" + ", ".join(fields) + ">> \\in {\n"
    "        " + ",\n        ".join(rows) + "\n    }\n"
    "====\n"
)
target = ROOT / "spec/session/LocalAdmission.tla"
if "--check" in sys.argv:
    if target.read_text() != text:
        raise SystemExit("LocalAdmission differs from the production frame guard")
else:
    target.write_text(text)
